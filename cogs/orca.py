import os
import json
import threading
import discord
from discord.ext import commands
from discord import app_commands
from flask import Flask, render_template, send_file

# =============================================================
# 1. FLASK WEB SERVER SETUP
# =============================================================
# Setting template_folder='.' allows Flask to find HTML files in the root folder!
app = Flask(__name__, template_folder='.')

@app.route("/")
def home():
    """Buyer Landing Page"""
    # Serves buyer index.html from root directory if present, otherwise returns text
    if os.path.exists("index.html"):
        return render_template("index.html")
    return "Orca Bot Web Server is Online!"

@app.route("/dashboard")
def staff_dashboard():
    """Staff Dashboard Page"""
    if os.path.exists("staff_index.html"):
        return render_template("staff_index.html")
    elif os.path.exists("index.html"):
        return render_template("index.html")
    return "Staff Dashboard template not found on server."

def run_web_server():
    # Uses host PORT env variable (default: 8080) for hosting platforms like Render
    port = int(os.environ.get("PORT", 8080))
    app.run(host="0.0.0.0", port=port)

# Start Flask in a background thread before running Discord bot
threading.Thread(target=run_web_server, daemon=True).start()

# =============================================================
# 2. DISCORD BOT SETUP
# =============================================================
# Replace with your production domain or ngrok URL
STAFF_DASHBOARD_URL = "https://orca-bot.onrender.com/dashboard"

intents = discord.Intents.default()
intents.guilds = True
intents.messages = True
intents.manage_roles = True
intents.manage_channels = True

bot = commands.Bot(command_prefix="!", intents=intents)

@bot.event
async def on_ready():
    print(f"Logged in as {bot.user} (ID: {bot.user.id})")
    
    # Global sync registers commands globally to keep the "/" Slash Command Badge
    try:
        synced = await bot.tree.sync()
        print(f"Synced {len(synced)} global slash command(s).")
    except Exception as e:
        print(f"Failed to sync commands: {e}")

